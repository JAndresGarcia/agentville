/** The engine exposes no locale (checked in claude-code.d.ts, 2.1.299), so the default is English, never a guess. */
export const DEFAULT_LANG: Lang = 'en'
export const langOf = (v: unknown): Lang => (v === 'es' || v === 'en' ? v : DEFAULT_LANG)

